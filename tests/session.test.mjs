import test from 'node:test';
import assert from 'node:assert/strict';
import { PreviewSession, commentMessage, batchMessage, MESSAGE_LIMIT } from '../src/session.mjs';

const doc = (text, path = 'D:\\example.md') => ({ path, text, name: 'example.md', checkedAt: new Date().toISOString() });
test('newest read wins across refresh and file switch; failure preserves the last successful preview', () => {
  const model = new PreviewSession();
  const first = model.begin('D:\\example.md');
  const latest = model.begin('D:\\example.md');
  assert.equal(model.success(first, doc('old')), null);
  assert.deepEqual(model.success(latest, doc('new')), { changed: true });
  const stale = model.begin(model.path);
  const switched = model.begin('D:\\other.md');
  assert.equal(model.success(stale, doc('wrong file')), null);
  assert.equal(model.document, null);
  model.success(switched, doc('other', 'D:\\other.md'));
  const failure = model.begin(model.path);
  assert.equal(model.failure(failure, 'locked'), true);
  assert.equal(model.document.text, 'other');
  assert.equal(model.error, 'locked');
  model.reset();
  assert.equal(model.success(failure, doc('closed')), null);
});

test('batch keeps ordered editable snapshots, binds file and conversation, and validates full message', () => {
  const model = new PreviewSession();
  model.success(model.begin('D:\\example.md'), doc('text A'));
  const add = (quote, comment) => { model.selectQuote(quote, 'A'); model.addComment('A', true, comment); };
  add('first quote', ' first comment ');
  add('second quote', 'second comment');
  assert.equal(model.draft, null);
  assert.deepEqual(model.comments.map(item => item.comment), ['first comment', 'second comment']);
  assert.throws(() => model.begin('D:\\other.md'), /先发送或清空/);
  assert.match(model.batchError('B', true), /目标会话/);
  assert.match(model.batchError('A', false), /不可见/);
  model.selectQuote('third quote', 'B');
  assert.throws(() => model.addComment('B', true, 'wrong target'), /目标会话/);
  model.updateComment(0, 'edited');
  model.updateComment(1, ' ');
  assert.match(model.batchError('A', true), /每条评论/);
  model.updateComment(1, 'second comment');
  assert.equal(model.batchError('A', true), '');
  assert.match(model.batchError('A', true, 'x'.repeat(4001)), /统一指令/);
  model.success(model.begin(model.path), doc('text A'));
  assert.ok(model.comments.every(item => !item.sourceChanged));
  model.success(model.begin(model.path), doc('text B'));
  assert.ok(model.comments.every(item => item.sourceChanged));
  assert.equal(model.batchError('A', true), '');
  const message = batchMessage(model.comments, ' execute these changes ');
  assert.match(message, /统一指令：\nexecute these changes/);
  assert.ok(message.indexOf('> first quote') < message.indexOf('> second quote'));
  assert.match(message, /引用快照/);
  assert.match(message, /评论：\nedited/);
  model.removeComment(-1);
  assert.equal(model.comments.length, 2);
  model.removeComment(0);
  assert.equal(model.comments[0].quote, 'second quote');
  model.failure(model.begin(model.path), 'missing');
  assert.equal(model.comments[0].sourceChanged, true);
  assert.equal(model.batchError('A', true), '');
  model.clearComments();
  model.success(model.begin(model.path), doc('text C'));
  add('x'.repeat(8000), 'x'.repeat(4000));
  const base = batchMessage(model.comments).length;
  const prefix = '\n\n统一指令：\n'.length;
  const instruction = 'x'.repeat(MESSAGE_LIMIT - base - prefix);
  assert.equal(batchMessage(model.comments, instruction).length, MESSAGE_LIMIT);
  assert.equal(model.batchError('A', true, instruction), '');
  assert.match(model.batchError('A', true, instruction + 'x'), /整批消息/);
  model.clearComments();
  add('"'.repeat(8000), '"'.repeat(4000));
  assert.equal(model.batchError('A', true, '"'.repeat(1000)), '');
  model.reset();
  assert.equal(model.comments.length, 0);
});

test('adding sends nothing; explicit batch sends once, preserves failures, and locks uncertain outcomes', async () => {
  const model = new PreviewSession();
  model.success(model.begin('D:\\example.md'), doc('text'));
  let calls = 0;
  let finish;
  const send = () => { calls++; return new Promise(resolve => { finish = resolve; }); };
  for (const quote of ['one', 'two']) { model.selectQuote(quote, 'A'); model.addComment('A', true, 'change'); }
  assert.equal(calls, 0);
  const pending = model.sendBatch(send, 'A', true, 'execute');
  assert.equal(calls, 1);
  assert.throws(() => model.updateComment(0, 'modified'));
  assert.throws(() => model.selectQuote('modified', 'A'));
  assert.throws(() => model.clearComments());
  assert.throws(() => model.begin(model.path));
  await assert.rejects(model.sendBatch(send, 'A', true));
  finish({ response: { error: 'rejected' } });
  assert.equal(await pending, 'rejected');
  assert.equal(model.comments.length, 2);
  assert.equal(model.uncertain, false);
  assert.equal(await model.sendBatch(() => Promise.reject(new Error('network')), 'A', true), 'uncertain');
  assert.equal(model.comments.length, 2);
  await assert.rejects(model.sendBatch(send, 'A', true), /未确认/);
  assert.throws(() => model.removeComment(0));
  model.uncertain = false;
  assert.equal(await model.sendBatch(() => new Promise(() => {}), 'A', true, '', 5), 'uncertain');
  assert.equal(model.comments.length, 2);
  model.uncertain = false;
  assert.equal(await model.sendBatch(async (message, id) => { calls++; assert.equal(id, 'A'); assert.match(message, /批量评论（2 条）/); return {}; }, 'A', true), 'sent');
  assert.equal(calls, 2);
  assert.equal(model.comments.length, 0);
  model.selectQuote('new', 'A'); model.addComment('A', true, 'change');
  const stale = model.sendBatch(send, 'A', true);
  model.reset();
  model.success(model.begin('D:\\example.md'), doc('new text'));
  model.selectQuote('fresh', 'A'); model.addComment('A', true, 'fresh comment');
  finish({});
  assert.equal(await stale, 'sent');
  assert.equal(model.comments[0].comment, 'fresh comment');
});
test('comment binds to readable content, exact file and conversation; changed or failed reads invalidate quote', () => {
  const model = new PreviewSession();
  model.success(model.begin('D:\\example.md'), doc('text A'));
  model.selectQuote('chosen\ntext', 'conversation-A');
  assert.equal(model.canSend('conversation-A', true, 'my comment'), true);
  assert.equal(model.canSend('conversation-B', true, 'my comment'), false);
  assert.equal(model.canSend('conversation-A', false, 'my comment'), false);
  assert.equal(model.canSend('conversation-A', true, ' '.repeat(3)), false);
  assert.equal(model.canSend('conversation-A', true, 'x'.repeat(4001)), false);
  const unchanged = model.begin(model.path);
  assert.equal(model.canSend('conversation-A', true, 'comment'), false);
  model.success(unchanged, doc('text A'));
  assert.equal(model.canSend('conversation-A', true, 'comment'), true);
  model.success(model.begin(model.path), doc('text B'));
  assert.equal(model.canSend('conversation-A', true, 'comment'), false);
  model.selectQuote('new quote', 'conversation-A');
  model.failure(model.begin(model.path), 'missing');
  assert.equal(model.draft.valid, false);
  assert.throws(() => model.selectQuote('quote', 'conversation-A'));
  const message = commentMessage({ path: 'D:\\example.md', quote: 'a\nb' }, ' comment ');
  assert.match(message, /文件：D:\\example\.md/);
  assert.match(message, /> a\n> b/);
  assert.match(message, /评论：\ncomment$/);
});
